#define filename "ghh"
#define ll                  long long
#define llmin               LLONG_MIN
#define llmax               LLONG_MAX
#define pb                  push_back
#define vect                vector
#define FOR(i , m , n)      for (int i=m ; i<n ; i++)
#define FOR_r(i , m , n)    for (int i=m ; i>n ; i--)
void IO(){
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    if (fopen(filename".inp" , "r"))
    {
    freopen(filename".inp" , "r" , stdin);
    freopen(filename".out" , "w" , stdout);
    }
}
bool solve(ll t){
    ll n = t;
    ll res = 1;
    for (int i=2 ; i*i <= n ; i++){
        ll coef = 1 , count = 1;
        while (n%i == 0){
            coef *= i;
            count += coef;
            n/=i;
        }
        res *= count;
    }
    if (n>1) res *= (n+1);
    return (res >= 2*t);
}
int main(){
    IO();
    ll t ; cin >> t;
    vect<ll> near;
    while (t--){
        ll n ; cin >> n;
        bool stat = solve(n);
        if (stat) near.push_back(n);
    }
    cout << near.size() << "\n";
    for (ll i : near) cout << i << "\n";

    return 0;
}


